// Generate provider command rules from the shared policy; --check never writes.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const policy = JSON.parse(
  readFileSync(new URL("./command-policy.json", import.meta.url), "utf8"),
);
const settingsUrl = new URL("../.claude/settings.json", import.meta.url);
const settings = JSON.parse(readFileSync(settingsUrl, "utf8"));
for (const decision of ["allow", "deny"]) {
  settings.permissions[decision] = [
    ...policy[decision].map((prefix) => `Bash(${prefix.join(" ")}:*)`),
    ...settings.permissions[decision].filter(
      (rule) => !rule.startsWith("Bash("),
    ),
  ];
}
const rules = [
  "# Generated by npm run agents:sync from .agents/command-policy.json.",
  "# Exact argv prefixes only; alternate flag placement may not match denials.",
  ...["allow", "deny"].flatMap((decision) =>
    policy[decision].map(
      (prefix) =>
        `prefix_rule(pattern=${JSON.stringify(prefix)}, decision="${decision === "deny" ? "forbidden" : "allow"}")`,
    ),
  ),
  "",
].join("\n");
let stale = false;
for (const [url, content] of [
  [
    settingsUrl,
    execFileSync(
      process.execPath,
      [
        fileURLToPath(
          new URL("../node_modules/@biomejs/biome/bin/biome", import.meta.url),
        ),
        "format",
        "--stdin-file-path=.claude/settings.json",
      ],
      { input: JSON.stringify(settings), encoding: "utf8" },
    ),
  ],
  [new URL("../.codex/rules/spacory.rules", import.meta.url), rules],
]) {
  if (process.argv.includes("--check")) {
    let current;
    try {
      current = readFileSync(url, "utf8");
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (current !== content) {
      console.error(
        `Stale command rules: ${url.pathname}; run npm run agents:sync`,
      );
      stale = true;
    }
  } else {
    mkdirSync(new URL(".", url), { recursive: true });
    writeFileSync(url, content);
  }
}
if (stale) process.exitCode = 1;
